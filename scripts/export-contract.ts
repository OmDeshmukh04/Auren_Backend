import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { buildOpenApi } from '../src/http/openapi.js';
import { allRoutes } from '../src/routes.js';
import { API_VERSION } from '../src/version.js';
import { PERMISSIONS, ROLE_DESCRIPTIONS, ROLE_PERMISSIONS, STAFF_ROLES } from '../src/auth/permissions.js';
import { z } from 'zod';
import { COLLECTION_DATA } from '../src/modules/content/schemas.js';

/**
 * Writes the frozen API contract for the frontend:
 *   contract/openapi.json   OpenAPI 3.1 (source of truth for transport)
 *   contract/api-types.d.ts TypeScript types generated from it (openapi-typescript)
 *   docs/PERMISSIONS.md     role x permission matrix and the permission each route requires
 */
const routes = allRoutes();
const document = buildOpenApi(routes, { version: API_VERSION, serverUrl: 'http://127.0.0.1:5181' });
mkdirSync('contract', { recursive: true });
writeFileSync('contract/openapi.json', `${JSON.stringify(document, null, 2)}\n`);
writeFileSync('contract/content-schemas.json', JSON.stringify(Object.fromEntries(Object.entries(COLLECTION_DATA).map(([key,schema])=>[key,z.toJSONSchema(schema,{unrepresentable:'any'})]))));
execFileSync(process.execPath, [resolve('node_modules/openapi-typescript/bin/cli.js'), 'contract/openapi.json', '-o', 'contract/api-types.d.ts'], { stdio: 'inherit' });

const yes = (role: (typeof STAFF_ROLES)[number], permission: (typeof PERMISSIONS)[number]) => (ROLE_PERMISSIONS[role].has(permission) ? '✓' : '');
const lines = [
  '# Permission matrix',
  '',
  'Generated by `npm run contract` from `src/auth/permissions.ts` and the route table. Do not edit by hand.',
  'The server enforces every check; the frontend should use `session.staff.permissions` only to shape the UI.',
  '',
  '## Roles',
  '',
  ...STAFF_ROLES.map(role => `- **${role}**: ${ROLE_DESCRIPTIONS[role]}`),
  '- **applicant draft session** (not a staff role): one application draft and its uploads only.',
  '',
  '## Role × permission',
  '',
  `| Permission | ${STAFF_ROLES.join(' | ')} |`,
  `| --- | ${STAFF_ROLES.map(() => ':---:').join(' | ')} |`,
  ...PERMISSIONS.map(permission => `| \`${permission}\` | ${STAFF_ROLES.map(role => yes(role, permission)).join(' | ')} |`),
  '',
  '## Routes',
  '',
  '| Method | Path | Access | Permission |',
  '| --- | --- | --- | --- |',
  ...routes.map(route => {
    const access = route.access;
    const permission = access.kind === 'staff' ? (access.permission ? `\`${access.permission}\`` : 'any staff') : '—';
    return `| ${route.method} | \`/api/v1${route.path}\` | ${access.kind} | ${permission} |`;
  }),
  ''
];
mkdirSync('docs', { recursive: true });
writeFileSync('docs/PERMISSIONS.md', lines.join('\n'));
console.log(`Contract written: ${routes.length} operations, version ${API_VERSION}.`);
